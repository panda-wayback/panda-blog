import fs from 'fs';
import path from 'path';
import type {
  Options as DocsPluginOptions,
  SidebarsConfig,
} from '@docusaurus/plugin-content-docs';
import {docsDefaults} from './docsDefaults';

type SidebarItemsGenerator = NonNullable<
  DocsPluginOptions['sidebarItemsGenerator']
>;
type SidebarItems = Awaited<ReturnType<SidebarItemsGenerator>>;
type SidebarItem = SidebarItems[number];

export type DocsSection = {
  id: string;
  dirName: string;
  sidebarId: string;
  label: string;
  description: string;
  position: number;
};

export type HomeSection = {
  id: string;
  label: string;
  to: string;
  description: string;
};

type NavMeta = {
  label?: string;
  position?: number;
  description?: string;
};

export function titleCase(slug: string): string {
  return slug
    .split(/[-_]/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ');
}

/** Folder-style labels that should get title-casing under global defaults. */
function looksLikeFolderSlug(label: string): boolean {
  return /^[a-z0-9]+(?:[-_][a-z0-9]+)+$/i.test(label) || /^[a-z0-9]+$/.test(label);
}

/**
 * First-level folders under docs/ become navbar sections.
 * Optional override: docs/<section>/_nav.json → { "label": "教程", "position": 1, "description": "这一栏写什么" }
 */
export function getDocsSections(
  docsDir = path.join(__dirname, 'docs'),
): DocsSection[] {
  if (!fs.existsSync(docsDir)) {
    return [];
  }

  const sections: DocsSection[] = [];

  for (const entry of fs.readdirSync(docsDir, {withFileTypes: true})) {
    if (!entry.isDirectory()) {
      continue;
    }
    if (entry.name.startsWith('.') || entry.name.startsWith('_')) {
      continue;
    }

    const dirName = entry.name;
    const navPath = path.join(docsDir, dirName, '_nav.json');
    let meta: NavMeta = {};
    if (fs.existsSync(navPath)) {
      meta = JSON.parse(fs.readFileSync(navPath, 'utf8')) as NavMeta;
    }

    sections.push({
      id: dirName,
      dirName,
      sidebarId: `${dirName}Sidebar`,
      label: meta.label ?? titleCase(dirName),
      description: meta.description ?? '',
      position: meta.position ?? Number.MAX_SAFE_INTEGER,
    });
  }

  return sections.sort(
    (a, b) => a.position - b.position || a.label.localeCompare(b.label),
  );
}

export function buildSidebars(
  sections = getDocsSections(),
): SidebarsConfig {
  return Object.fromEntries(
    sections.map((section) => [
      section.sidebarId,
      [{type: 'autogenerated' as const, dirName: section.dirName}],
    ]),
  );
}

export function buildNavbarDocItems(sections = getDocsSections()) {
  return sections.map((section) => ({
    type: 'docSidebar' as const,
    sidebarId: section.sidebarId,
    label: section.label,
    position: 'left' as const,
  }));
}

function docRelPath(absDir: string, fileName: string): string {
  const slug = fileName.replace(/\.mdx?$/, '');
  return path
    .relative(path.join(__dirname, 'docs'), path.join(absDir, slug))
    .split(path.sep)
    .join('/');
}

/** Prefer a page in this folder, then the first page in a subfolder. */
function findFirstDocRelPath(absDir: string): string | null {
  const entries = fs
    .readdirSync(absDir, {withFileTypes: true})
    .filter((entry) => !entry.name.startsWith('.') && !entry.name.startsWith('_'))
    .sort((a, b) => a.name.localeCompare(b.name));

  for (const entry of entries) {
    if (entry.isFile() && /\.mdx?$/.test(entry.name)) {
      return docRelPath(absDir, entry.name);
    }
  }

  for (const entry of entries) {
    if (!entry.isDirectory()) {
      continue;
    }
    const nested = findFirstDocRelPath(path.join(absDir, entry.name));
    if (nested) {
      return nested;
    }
  }
  return null;
}

/** Homepage cards: one per top-level docs folder, same source as the navbar. */
export function buildHomeSections(sections = getDocsSections()): HomeSection[] {
  return sections.flatMap((section) => {
    const firstDoc = findFirstDocRelPath(
      path.join(__dirname, 'docs', section.dirName),
    );
    if (!firstDoc) {
      return [];
    }
    return [
      {
        id: section.id,
        label: section.label,
        to: `/docs/${firstDoc}`,
        description: section.description,
      },
    ];
  });
}

/** Footer links derived from the same docs/ sections as the navbar. */
export function buildFooterDocItems(sections = getDocsSections()) {
  return sections.flatMap((section) => {
    const firstDoc = findFirstDocRelPath(
      path.join(__dirname, 'docs', section.dirName),
    );
    if (!firstDoc) {
      return [];
    }
    return [{label: section.label, to: `/docs/${firstDoc}`}];
  });
}

function applyCategoryDefaults(items: SidebarItems): SidebarItems {
  const {category} = docsDefaults;

  return items.map((item): SidebarItem => {
    if (item.type !== 'category') {
      return item;
    }

    let label = item.label;
    if (category.titleCaseLabel && looksLikeFolderSlug(label)) {
      // Only rewrite labels that still look like raw folder names.
      // Custom labels from _category_.json are left alone.
      label = titleCase(label);
    }

    return {
      ...item,
      label,
      items: applyCategoryDefaults(item.items),
      link:
        category.generatedIndex && item.link === undefined
          ? {type: 'generated-index', title: label}
          : item.link,
      collapsible: item.collapsible ?? category.collapsible,
      collapsed: item.collapsed ?? category.collapsed,
    };
  });
}

/** Apply docsDefaults to every autogenerated sidebar category. */
export const sidebarItemsGenerator: SidebarItemsGenerator = async (args) => {
  const items = await args.defaultSidebarItemsGenerator(args);
  return applyCategoryDefaults(items);
};
